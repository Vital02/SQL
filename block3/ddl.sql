CREATE TABLE IF NOT EXISTS dim_orbit_types (
    orbit_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(10) NOT NULL UNIQUE,
    description TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS dim_satellites (
    satellite_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    orbit_type_id INTEGER NOT NULL REFERENCES dim_orbit_types (orbit_type_id),
    launch_date DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS dim_statuses (
    status_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_name VARCHAR(20) NOT NULL UNIQUE,
    description TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS fact_telemetry (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    satellite_id INTEGER NOT NULL REFERENCES dim_satellites (satellite_id),
    status_id INTEGER NOT NULL REFERENCES dim_statuses (status_id),
    distance NUMERIC(12,3) NOT NULL CHECK (distance >= 0),
    signal_strength NUMERIC(6,2)  NOT NULL,
    battery_level SMALLINT NOT NULL CHECK (battery_level BETWEEN 0 AND 100),
    event_time TIMESTAMP NOT NULL
);